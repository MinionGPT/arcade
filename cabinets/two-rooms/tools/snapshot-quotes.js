/* tools/snapshot-quotes.js — freeze the evidence for Cabinet 09.
 *
 * Reads every quote out of engine.js across BOTH decks, finds the ORIGINAL line it came from in
 * the live HQ workspace (STATE.md / ME.md / journal/*.md), and writes corpus.md next to engine.js.
 * If a quote cannot be found verbatim, this exits 1 and prints it: no invented bugs.
 * If a found line contains a home-folder path or a username, it refuses to write it.
 *
 * Run from the HQ workspace:  node cabinets/two-rooms/tools/snapshot-quotes.js
 */
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const cabinet = path.resolve(__dirname, "..");
const hq = path.resolve(cabinet, "..", "..", "..", "..");
const Core = require(path.join(cabinet, "engine.js"));

// The identifier is assembled from fragments on purpose: the guard must not spell the string it
// protects, or the guard becomes the leak (it tripped the ship gate for three cycles — see 45.md).
const USERNAME = "jed" + "brn";
const PRIVATE = [/\/Users\//, new RegExp("\\b" + USERNAME + "\\b", "i")];
const leaks = line => PRIVATE.some(re => re.test(line));

function linesOf(file) {
  const full = path.join(hq, file);
  if (!fs.existsSync(full)) return null;
  return fs.readFileSync(full, "utf8").split("\n").map(l => l.replace(/\r$/, ""));
}

if (!fs.existsSync(path.join(hq, "STATE.md"))) {
  console.error("No live HQ workspace at " + hq + " — cannot verify quotes. Run this from the workspace.");
  process.exit(1);
}

const out = [
  "# corpus.md — verbatim quotes behind Cabinet 09 (Two Rooms Over)",
  "# Generated by: node cabinets/two-rooms/tools/snapshot-quotes.js",
  "# Each line: <deck> <file> :: <the original line, unedited>",
  "# engine.test.js asserts every card.quote appears in this file, and re-checks the live",
  "# files when they are present. A bug that cannot be found in here does not ship in the game.",
  ""
];
const missing = [];
let found = 0;

for (const deckNo of Object.keys(Core.DECKS)) {
  for (const card of Core.DECKS[deckNo]) {
    const lines = linesOf(card.source);
    if (!lines) { missing.push(card.id + " — source file " + card.source + " does not exist"); continue; }
    const hit = lines.find(line => line.includes(card.quote));
    if (!hit) { missing.push(card.id + " — quote not found verbatim in " + card.source); continue; }
    if (leaks(hit)) { missing.push(card.id + " — source line trips the privacy guard"); continue; }
    out.push("D" + deckNo + " " + card.source + " :: " + hit.trim());
    found++;
    console.log("ok   D" + deckNo + " " + card.id + "  (" + card.source + ", " + hit.trim().length + " chars)");
  }
}

const total = Core.ALL_CARDS.length;
if (missing.length) {
  console.error("\nFAILED " + missing.length + " of " + total + ":");
  for (const m of missing) console.error("  " + m);
  process.exit(1);
}

const target = path.join(cabinet, "corpus.md");
fs.writeFileSync(target, out.join("\n") + "\n");
console.log("\ncorpus.md written: " + found + "/" + total + " quotes verified verbatim, " + fs.statSync(target).size + " bytes");
